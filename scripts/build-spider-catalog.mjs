/**
 * 生成 OmniBox-Spider 内置脚本目录。
 *
 * 该脚本只在开发时手动运行（node scripts/build-spider-catalog.mjs），
 * 产物 src/backend/data/spider-catalog.ts 直接入库，运行时不依赖 GitHub API，
 * 因此 Serverless 冷启动没有额外网络开销，也不会触发 API 限流。
 *
 * 同步脚本代码时才按需访问 raw.githubusercontent.com。
 */
import { execFile } from "node:child_process"
import { promisify } from "node:util"
import { createHash } from "node:crypto"
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const run = promisify(execFile)
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const REPO = "Silent1566/OmniBox-Spider"
const BRANCH = "main"
const EXCLUDE_PREFIXES = ["tests/", "直播/", "已失效待修复/", "模板/"]
const CATEGORY_MAP = {
  影视: "movie",
  动漫: "anime",
  短剧: "short",
  音乐: "music",
  听书: "audiobook",
  导航: "nav",
  综合: "mixed",
  流媒体: "stream",
  教育: "edu",
  定时任务: "task",
  拦截器: "interceptor",
  Emby: "emby",
}

async function curl(url, binary = false) {
  const args = ["-sS", "--max-time", "30", "-L", url]
  const { stdout } = await run("curl", args, {
    maxBuffer: 64 * 1024 * 1024,
    encoding: binary ? "buffer" : "utf8",
  })
  return stdout
}

function parseMeta(source, filename) {
  const meta = {}
  const re = /^\s*(?:\/\/|#)\s*@([\w-]+)\s+(.+?)\s*$/gm
  let m
  while ((m = re.exec(source))) meta[m[1].toLowerCase()] = m[2]
  return {
    name: meta.name || filename.replace(/\.(js|py)$/i, ""),
    author: meta.author || "",
    description: meta.description || "",
    version: meta.version || "",
    downloadUrl: meta.downloadurl || "",
    dependencies: meta.dependencies || "",
    indexs: Number(meta.indexs || 0) || 0,
  }
}

async function main() {
  const treeUrl = `https://api.github.com/repos/${REPO}/git/trees/${BRANCH}?recursive=1`
  const tree = JSON.parse(await curl(treeUrl))
  if (tree.truncated) throw new Error("GitHub tree truncated, cannot build full catalog")

  const scripts = (tree.tree || []).filter(
    (x) =>
      x.type === "blob" &&
      /\.(js|py)$/i.test(x.path) &&
      !EXCLUDE_PREFIXES.some((p) => x.path.startsWith(p)),
  )
  console.log(`[catalog] ${scripts.length} scripts from ${REPO}`)

  const items = []
  const queue = [...scripts]
  const workers = Array.from({ length: 8 }, async () => {
    while (queue.length) {
      const file = queue.shift()
      const parts = file.path.split("/")
      const folder = parts[0]
      const filename = parts[parts.length - 1]
      const type = /\.py$/i.test(filename) ? "Python" : "JavaScript"
      const categoryKey = CATEGORY_MAP[folder] || "other"
      const rawUrl = `https://raw.githubusercontent.com/${REPO}/${BRANCH}/${encodeURI(file.path)}`
      let source = ""
      try {
        source = await curl(rawUrl, true).then((b) => b.toString("utf8"))
      } catch (e) {
        console.warn(`[catalog] fetch failed: ${file.path} - ${e.message}`)
      }
      const meta = parseMeta(source, filename)
      const id = `${categoryKey}-${createHash("sha1").update(file.path).digest("hex").slice(0, 8)}`
      const priority = meta.indexs > 0 ? Math.max(1, 101 - meta.indexs) : 50
      const tags = [folder, type]
      if (meta.dependencies) tags.push(...meta.dependencies.split(/[,，]/).map((x) => x.trim()).filter(Boolean).slice(0, 2))
      items.push({
        id,
        name: meta.name,
        path: file.path,
        category: folder,
        categoryKey,
        type,
        version: meta.version,
        author: meta.author,
        description: meta.description,
        dependencies: meta.dependencies,
        priority,
        tags: [...new Set(tags)].slice(0, 4),
        size: file.size || 0,
        supported: type === "JavaScript",
        url: rawUrl,
      })
      process.stdout.write(".")
    }
  })
  await Promise.all(workers)
  console.log("")

  items.sort((a, b) => (b.priority - a.priority) || a.name.localeCompare(b.name, "zh-CN"))
  const out = `// AUTO-GENERATED by scripts/build-spider-catalog.mjs — do not edit manually.\n` +
    `// Source: https://github.com/${REPO} (${BRANCH})\n` +
    `// Generated: ${new Date().toISOString()}\n\n` +
    `export type SpiderCatalogItem = {\n` +
    `  id: string\n  name: string\n  path: string\n  category: string\n  categoryKey: string\n` +
    `  type: "JavaScript" | "Python"\n  version: string\n  author: string\n  description: string\n` +
    `  dependencies: string\n  priority: number\n  tags: string[]\n  size: number\n` +
    `  supported: boolean\n  url: string\n}\n\n` +
    `export const SPIDER_LIBRARY = {\n` +
    `  repo: "${REPO}",\n  branch: "${BRANCH}",\n` +
    `  updatedAt: "${new Date().toISOString()}",\n  count: ${items.length},\n} as const\n\n` +
    `export const SPIDER_CATALOG: SpiderCatalogItem[] = ${JSON.stringify(items, null, 2)}\n`

  const dest = path.join(ROOT, "src", "backend", "data", "spider-catalog.ts")
  fs.writeFileSync(dest, out, "utf8")
  console.log(`[catalog] wrote ${dest} (${items.length} items, ${(out.length / 1024).toFixed(1)} KB)`)
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
